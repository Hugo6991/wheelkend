#!/usr/bin/env python3
"""Self-host subset webfonts (removes the Google Fonts dependency — required
for mainland-China access, nice-to-have everywhere).

1. collects every character used by the site (src/ + data/cities/*.json)
2. downloads Noto Serif TC / Noto Sans TC variable fonts (google/fonts, OFL)
3. instances the weights the site uses (Serif 900; Sans 400, 700)
4. subsets to the collected charset and writes woff2 + fonts.css into
   vendor/fonts/, plus charset.txt used by build.py to verify coverage

Requires: fonttools + brotli (both present in the anaconda python).
Run again whenever city data adds new characters (build.py warns loudly)."""
import os, string, sys, urllib.request
from io import BytesIO

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "vendor", "fonts")
os.makedirs(OUT, exist_ok=True)
UA = {"User-Agent": "wheelkend/1.0 (personal project)"}

FONTS = {
    "NotoSerifTC": ("https://github.com/google/fonts/raw/main/ofl/notoseriftc/NotoSerifTC%5Bwght%5D.ttf", [900]),
    "NotoSansTC":  ("https://github.com/google/fonts/raw/main/ofl/notosanstc/NotoSansTC%5Bwght%5D.ttf", [400, 700]),
}
FAMILY = {"NotoSerifTC": "Noto Serif TC", "NotoSansTC": "Noto Sans TC"}

# ---- 1. charset from everything user-visible ----
chars = set(string.printable)
sources = [os.path.join(ROOT, "src", "index.html"), os.path.join(ROOT, "src", "app.js")]
data_dir = os.path.join(ROOT, "data", "cities")
sources += [os.path.join(data_dir, f) for f in os.listdir(data_dir) if f.endswith(".json")]
for path in sources:
    chars.update(open(path, encoding="utf-8").read())
# common punctuation/symbols that may appear in future copy
chars.update("〇一二三四五六七八九十©・——「」『』（）？！；：、，⋯○●★☆℃")
chars = {c for c in chars if c.isprintable() or c in "\n\t"}
charset = "".join(sorted(chars))
open(os.path.join(OUT, "charset.txt"), "w", encoding="utf-8").write(charset)
print(f"charset: {len(charset)} chars from {len(sources)} files")

# ---- 2-4. download, instance, subset ----
css = ["/* generated by scripts/build_fonts.py — self-hosted subsets (SIL OFL 1.1) */"]
for stem, (url, weights) in FONTS.items():
    print(f"downloading {stem}...", flush=True)
    raw = urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=120).read()
    for w in weights:
        font = TTFont(BytesIO(raw))
        instantiateVariableFont(font, {"wght": w}, inplace=True)
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["*"]
        opts.name_IDs = ["*"]
        opts.notdef_outline = True
        subsetter = subset.Subsetter(options=opts)
        subsetter.populate(text=charset)
        subsetter.subset(font)
        out_path = os.path.join(OUT, f"{stem}-{w}.woff2")
        font.save(out_path)
        kb = os.path.getsize(out_path) // 1024
        print(f"  {stem}-{w}.woff2: {kb} KB")
        css.append(
            "@font-face {\n"
            f"  font-family: '{FAMILY[stem]}';\n"
            f"  font-weight: {w};\n"
            "  font-style: normal;\n"
            "  font-display: swap;\n"
            f"  src: url('{stem}-{w}.woff2') format('woff2');\n"
            "}")

open(os.path.join(OUT, "fonts.css"), "w", encoding="utf-8").write("\n".join(css) + "\n")
print(f"wrote {OUT}/fonts.css")
